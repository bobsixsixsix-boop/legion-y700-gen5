#!/bin/bash
# y14 prep step 3: branch y14 in /usr/local/src/linux-t52 = t52-base + our stack, ONE COMMIT PER PATCH FILE,
# then export every commit with our original file name to /root/y14-export/ (copied to linux/kernel-y14/patches/).
# mbox patches go through git am (keeps author/date); header-only or bare diffs through git apply + commit.
set -euo pipefail
W=/usr/local/src/linux-t52; IN=/root/y14-in; EXP=/root/y14-export
cd $W
export GIT_COMMITTER_NAME=y700-kbuild GIT_COMMITTER_EMAIL=y700-kbuild@localhost
G="git -c gc.auto=0 -c maintenance.auto=0"
DEF_AUTHOR="y700 workspace <304558835+bobsixsixsix-boop@users.noreply.github.com>"
[ "$(git branch --show-current)" = y14-dry ] && git reset -q --hard
[ -z "$(git status --porcelain --untracked-files=no)" ] || { echo "linux-t52 has local changes"; exit 1; }
git rev-parse -q --verify refs/heads/y14 >/dev/null && { echo "branch y14 exists; delete it first (git branch -D y14)"; exit 1; }
$G switch -q -c y14 t52-base
series="$IN/00y1-*.patch $IN/00y2-*.patch $IN/00y3-*.patch $IN/00y4-*.patch $IN/00y5-*.patch
/root/y4-patches/0540-*-sm8850.patch /root/y4-patches/0620-*.patch /root/y4-patches/0621-*.patch /root/y4-patches/0622-*.patch
/root/y6-patches/1030-*.patch /root/y6-patches/1031-*.patch /root/y6-patches/1032-*.patch /root/y7-patches/1033-*.patch
/root/y8-patches/1041-*.patch /root/y8-patches/1042-*.patch /root/y8-patches/1043-*.patch
/root/y13-patches/1046-*.patch /root/y13-patches/1047-*.patch /root/y13-patches/1048-*.patch /root/y13-patches/1049-*.patch /root/y13-patches/1050-*.patch"
rm -rf $EXP; mkdir -p $EXP
: > $EXP/series
for p in $series; do
	[ -f "$p" ] || { echo "MISSING $p"; exit 1; }
	name=$(basename "$p")
	if head -1 "$p" | grep -q '^From [0-9a-f]\{40\} '; then
		# mbox (format-patch): git am; -3 falls back to a 3-way merge through the index lines (00y2 needs it)
		$G am -q -3 --no-gpg-sign "$p"
		how=am
	else
		$G apply --index "$p"
		author=$(sed -n '1,/^---$/{s/^From: //p}' "$p" | head -1)
		subject=$(sed -n '1,/^---$/{s/^Subject: \(\[PATCH[^]]*\] \)\{0,1\}//p}' "$p" | head -1)
		case "$name" in
		1041-*) subject="wifi: ath12k: apply BSS_CHANGED_PS from vif_cfg_changed to every station link"
			body="mac80211 reports BSS_CHANGED_PS through vif_cfg_changed (a vif-level change), but ath12k only
handled it in the per-link bss_info_changed, which never sees it, so station power save was never
switched on in the firmware. Handle it in ath12k_mac_op_vif_cfg_changed() for every link (y8).
Upstream had the same fix (4b66d18918f8) and reverted it (9222582ec524, WCN7850 throughput).
MODULE_VERSION(\"y700-1041\") marks the build (kbuild asserts it).
Generated by linux/kernel-y8/make-1041.py on the tablet tree." ;;
		*) body=$(sed -n '/^Subject: /,/^---$/p' "$p" | sed '1d;$d' | sed '/./,$!d') ;;
		esac
		# an author line without a mail address (1049, 1050 name their origin there): keep it in the message
		if ! printf '%s' "$author" | grep -q '<[^>]*@[^>]*>'; then
			[ -n "$author" ] && body="$body

Origin (as recorded in the patch file): $author"
			author=$DEF_AUTHOR
		fi
		printf '%s\n\n%s\n\ny700 patch file: %s\n' "$subject" "$body" "$name" > /tmp/y14-msg
		$G commit -q --no-gpg-sign --author="$author" -F /tmp/y14-msg
		rm -f /tmp/y14-msg
		how=apply
	fi
	git format-patch -q -1 --stdout HEAD > "$EXP/$name"
	echo "$name" >> $EXP/series
	echo "$how  $(git log -1 --format='%h %an: %s') <- $name"
done
git log --oneline t52-base..y14 | wc -l
echo "=== file comparison against linux-t47 (y13; signal.c and ath12k/core.c differ by upstream v7.3 changes only)"
for f in $(git -C /usr/local/src/linux-t47 diff --name-only); do
	if cmp -s "$f" "/usr/local/src/linux-t47/$f"; then echo "SAME     $f"; else echo "DIFFERS  $f"; fi
done
# the exported files re-create the same tree on t52-base (temporary index; the worktree is not touched)
export GIT_INDEX_FILE=/tmp/y14-index
git read-tree t52-base
while read -r name; do git apply --cached "$EXP/$name"; done < $EXP/series
if [ "$(git write-tree)" = "$(git rev-parse "y14^{tree}")" ]; then echo "EXPORT_REPLAY_OK: t52-base + exported series == y14 tree"; else echo "EXPORT_REPLAY_MISMATCH"; exit 1; fi
rm -f /tmp/y14-index
